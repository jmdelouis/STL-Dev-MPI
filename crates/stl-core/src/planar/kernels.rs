//! at scale 0 on a 256 x 256 grid, inverse transformed, shifted, cropped to
//! 5 x 5 and made zero-mean.  STL-Dev builds the Fourier bank in float32
//! (`torch.empty` with the default dtype) before casting the crop to
//! complex128, so the values are stored here as dumped
//! (`tools/dump_planar_reference.py`, fixture `planar/kernels`) rather than
//! recomputed.  The same kernel is applied at every level, whatever the
//! image size.
//!
//! The smoothing kernel of the decimation is the 6 x 6 cropped raised
//! cosine of `_get_smooth_kernel` (stride 2, `pad_before = 2`,
//! `pad_after = 3`).

